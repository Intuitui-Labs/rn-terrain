import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { TopologicalSubstrateProfiler } from '../src/topological-substrate-profiler.js';

describe('TopologicalSubstrateProfiler', () => {
  let tempDir: string;

  beforeEach(() => {
    tempDir = fs.mkdtempSync(path.join(os.tmpdir(), 'substrate-test-'));
  });

  afterEach(() => {
    try {
      fs.rmSync(tempDir, { recursive: true, force: true });
    } catch {}
  });

  it('classifies project as PURE_CNG when native folders are absent and app.json exists', () => {
    fs.writeFileSync(
      path.join(tempDir, 'package.json'),
      JSON.stringify({
        name: 'pure-cng-app',
        dependencies: {
          expo: '^52.0.0',
          'expo-router': '~4.0.0',
        },
      })
    );

    fs.writeFileSync(
      path.join(tempDir, 'app.json'),
      JSON.stringify({
        expo: {
          name: 'Pure CNG App',
          slug: 'pure-cng',
          plugins: ['expo-router'],
        },
      })
    );

    const profiler = new TopologicalSubstrateProfiler(tempDir);
    const profile = profiler.profile();

    expect(profile.governance.model).toBe('PURE_CNG');
    expect(profile.governance.hasAndroidDir).toBe(false);
    expect(profile.governance.hasIosDir).toBe(false);
    expect(profile.governance.nativePatchTargetAdvice).toContain('Native directories are ephemeral');
    expect(profile.shell.type).toBe('CUSTOM_OR_NONE'); // app/ dir not created yet
  });

  it('classifies project as COMMITTED_PREBUILD (Dirty CNG) when native folders exist with @generated markers', () => {
    fs.writeFileSync(
      path.join(tempDir, 'package.json'),
      JSON.stringify({
        name: 'prebuilt-app',
        dependencies: {
          expo: '^52.0.0',
          'react-native-nitro-modules': '^0.22.0',
        },
      })
    );

    fs.writeFileSync(
      path.join(tempDir, 'app.json'),
      JSON.stringify({
        expo: {
          name: 'Prebuilt App',
          slug: 'prebuilt',
          plugins: [
            [
              'expo-build-properties',
              {
                android: {
                  compileSdkVersion: 37,
                },
              },
            ],
          ],
        },
      })
    );

    const androidAppDir = path.join(tempDir, 'android', 'app');
    fs.mkdirSync(androidAppDir, { recursive: true });
    fs.writeFileSync(
      path.join(androidAppDir, 'build.gradle'),
      `// @generated by expo-build-properties\ncompileSdkVersion 37\n`
    );

    const profiler = new TopologicalSubstrateProfiler(tempDir);
    const profile = profiler.profile();

    expect(profile.governance.model).toBe('COMMITTED_PREBUILD');
    expect(profile.governance.hasGeneratedMarkers).toBe(true);
    expect(profile.platform.compileSdkVersion).toBe(37);
    expect(profile.platform.isAndroid15EdgeToEdgeEnforced).toBe(true);
    expect(profile.autolinking.hasNitroModules).toBe(true);
    expect(profile.autolinking.hasExpoModulesCore).toBe(true);
    expect(profile.autolinking.potentialCollisions.length).toBeGreaterThan(0);
  });

  it('detects config drift when committed build.gradle differs from expo-build-properties', () => {
    fs.writeFileSync(
      path.join(tempDir, 'package.json'),
      JSON.stringify({
        name: 'drift-app',
        dependencies: { expo: '^52.0.0' },
      })
    );

    fs.writeFileSync(
      path.join(tempDir, 'app.json'),
      JSON.stringify({
        expo: {
          plugins: [
            [
              'expo-build-properties',
              {
                android: {
                  compileSdkVersion: 37,
                },
              },
            ],
          ],
        },
      })
    );

    const androidAppDir = path.join(tempDir, 'android', 'app');
    fs.mkdirSync(androidAppDir, { recursive: true });
    // Committed file has compileSdkVersion 34 (diverged from plugin's 37)
    fs.writeFileSync(
      path.join(androidAppDir, 'build.gradle'),
      `// @generated by expo-build-properties\ncompileSdkVersion 34\n`
    );

    const profiler = new TopologicalSubstrateProfiler(tempDir);
    const profile = profiler.profile();

    expect(profile.configDrift.hasDrift).toBe(true);
    expect(profile.configDrift.driftViolations[0].property).toBe('compileSdkVersion');
    expect(profile.configDrift.driftViolations[0].pluginValue).toBe(37);
    expect(profile.configDrift.driftViolations[0].committedValue).toBe(34);
  });

  it('classifies project as PURE_BARE when app.json is missing and native folders exist', () => {
    fs.writeFileSync(
      path.join(tempDir, 'package.json'),
      JSON.stringify({
        name: 'bare-rn-app',
        dependencies: {
          'react-native': '0.78.0',
        },
      })
    );

    fs.mkdirSync(path.join(tempDir, 'android'), { recursive: true });
    fs.mkdirSync(path.join(tempDir, 'ios'), { recursive: true });

    const profiler = new TopologicalSubstrateProfiler(tempDir);
    const profile = profiler.profile();

    expect(profile.governance.model).toBe('PURE_BARE');
    expect(profile.governance.hasAppJson).toBe(false);
    expect(profile.governance.nativePatchTargetAdvice).toContain('Pure Bare React Native');
  });

  it('detects Expo Router shell and modal route groups in app/ directory', () => {
    fs.writeFileSync(
      path.join(tempDir, 'package.json'),
      JSON.stringify({
        name: 'router-app',
        dependencies: {
          expo: '^52.0.0',
          'expo-router': '^4.0.0',
        },
      })
    );

    fs.writeFileSync(
      path.join(tempDir, 'app.json'),
      JSON.stringify({ expo: { name: 'Router App' } })
    );

    const appDir = path.join(tempDir, 'app', '(modals)');
    fs.mkdirSync(appDir, { recursive: true });
    fs.writeFileSync(path.join(appDir, 'gate.tsx'), 'export default function Gate() { return null; }');

    const profiler = new TopologicalSubstrateProfiler(tempDir);
    const profile = profiler.profile();

    expect(profile.shell.type).toBe('EXPO_ROUTER');
    expect(profile.shell.hasFileSystemRouting).toBe(true);
    expect(profile.shell.modalRouteGroupsCount).toBe(1);
    expect(profile.shell.guidance).toContain('Expo Router active');
  });
});
