import { describe, it, expect } from 'vitest';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { HoneypotEngine, CANONICAL_HONEYPOT_TRAPDOORS } from '../src/honeypot-engine.js';
import { AgentGuardrail } from '../src/agent-guardrail.js';

describe('Parametric Hallucination Honeypot Engine', () => {
  const engine = new HoneypotEngine();

  it('generates valid ambient shadow typings with never types and trapdoor annotations', () => {
    const dts = engine.generateHoneypotDts();
    expect(dts).toContain('declare module \'@react-native-async-storage/async-storage\'');
    expect(dts).toContain('multiGetBatch: never');
    expect(dts).toContain('createSpringConfig: never');
    expect(dts).toContain('MultiTouchPan: never');
    expect(dts).toContain('@deprecated TRAPDOOR:');
  });

  it('writes honeypots.d.ts to target directory', () => {
    const tempDir = path.join(process.cwd(), '.terrain-test-honeypots');
    try {
      const writtenPath = engine.writeHoneypotDefinitions(tempDir);
      expect(fs.existsSync(writtenPath)).toBe(true);
      const content = fs.readFileSync(writtenPath, 'utf-8');
      expect(content).toContain('GENERATED BY RN-TERRAIN PARAMETRIC HONEYPOT ENGINE');
    } finally {
      if (fs.existsSync(tempDir)) {
        fs.rmSync(tempDir, { recursive: true, force: true });
      }
    }
  });

  it('detects hallucinated AsyncStorage.multiGetBatch() via AST MemberExpression', () => {
    const badCode = `
      import AsyncStorage from '@react-native-async-storage/async-storage';
      export async function fetchTokens(keys: string[]) {
        return await AsyncStorage.multiGetBatch(keys);
      }
    `;

    const report = engine.detectHoneypots(badCode, 'TokenStore.ts');
    expect(report.hasTrapdoorTriggered).toBe(true);
    expect(report.violations.length).toBeGreaterThan(0);
    expect(report.violations[0].symbol).toBe('multiGetBatch');
    expect(report.violations[0].severity).toBe('TRAPDOOR_PARAMETRIC_HALLUCINATION');
    expect(report.violations[0].confidenceScore).toBe(1.0);
    expect(report.remediationPrompt).toContain('PARAMETRIC HALLUCINATION TRAPDOOR TRIGGERED');
    expect(report.remediationPrompt).toContain("AsyncStorage.multiGet(['key1', 'key2'])");
  });

  it('detects hallucinated Reanimated.createSpringConfig() via direct call and import', () => {
    const badCode = `
      import { createSpringConfig } from 'react-native-reanimated';
      const config = createSpringConfig({ damping: 10 });
    `;

    const report = engine.detectHoneypots(badCode, 'Animation.tsx');
    expect(report.hasTrapdoorTriggered).toBe(true);
    expect(report.violations.some((v) => v.symbol === 'createSpringConfig')).toBe(true);
  });

  it('detects hallucinated Gesture.MultiTouchPan() in gesture definitions', () => {
    const badCode = `
      import { Gesture } from 'react-native-gesture-handler';
      const pan = Gesture.MultiTouchPan();
    `;

    const report = engine.detectHoneypots(badCode, 'GestureComponent.tsx');
    expect(report.hasTrapdoorTriggered).toBe(true);
    expect(report.violations[0].symbol).toBe('MultiTouchPan');
    expect(report.violations[0].canonicalRemediation).toContain('Gesture.Pan().minPointers(2)');
  });

  it('respects file-level and line-level ignore comments', () => {
    const ignoredFile = `
      // @rn-terrain-ignore-file
      import AsyncStorage from '@react-native-async-storage/async-storage';
      const x = AsyncStorage.multiGetBatch(['a']);
    `;
    expect(engine.detectHoneypots(ignoredFile).hasTrapdoorTriggered).toBe(false);

    const ignoredLine = `
      import AsyncStorage from '@react-native-async-storage/async-storage';
      // @rn-terrain-ignore
      const x = AsyncStorage.multiGetBatch(['a']);
    `;
    expect(engine.detectHoneypots(ignoredLine).hasTrapdoorTriggered).toBe(false);
  });

  it('allows valid modern canonical code without false positives', () => {
    const cleanCode = `
      import AsyncStorage from '@react-native-async-storage/async-storage';
      import { withSpring } from 'react-native-reanimated';
      import { Gesture } from 'react-native-gesture-handler';

      export async function loadData() {
        const pan = Gesture.Pan().minPointers(2);
        const spring = withSpring(100, { damping: 15 });
        return await AsyncStorage.multiGet(['k1', 'k2']);
      }
    `;

    const report = engine.detectHoneypots(cleanCode, 'CleanComponent.tsx');
    expect(report.hasTrapdoorTriggered).toBe(false);
    expect(report.violations.length).toBe(0);
  });

  it('integrates seamlessly with AgentGuardrail to block hallucinated changes with remediation prompt', () => {
    const guardrail = new AgentGuardrail();
    const badDiff = `
      import AsyncStorage from '@react-native-async-storage/async-storage';
      export const getBatch = () => AsyncStorage.multiGetBatch(['session']);
    `;

    const verdict = guardrail.verify({
      packageName: '@react-native-async-storage/async-storage',
      targetVersion: '2.0.0',
      codeSnippet: badDiff,
    });

    expect(verdict.allowed).toBe(false);
    expect(verdict.status).toBe('BLOCKED_SEVERED_API');
    expect(verdict.severedViolations.length).toBeGreaterThan(0);
    expect(verdict.severedViolations[0].symbol).toBe('multiGetBatch');
    expect(verdict.remediationPrompt).toContain('PARAMETRIC HALLUCINATION TRAPDOOR TRIGGERED');
  });
});
